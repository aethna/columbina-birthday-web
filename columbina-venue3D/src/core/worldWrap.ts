/**
 * 伪大世界（环形地图）—— 世界尺度常量 + **严格周期**的程序化噪声。
 *
 * ## 为什么要「周期」而不是「把坐标取模」
 * 用户 m01512：「如果玩家一直向上走到边界，走出去之后就会从地图下边界进来
 * （并非传送而是地图拼接），如此循环。」
 *
 * ⚠️ 直觉上会想「把坐标 `mod W` 一下不就行了」—— **不行**。
 * `mod` 只是给同一个点换了个名字：Perlin 噪声在 `x = W` 处与 `x = 0` 处的值毫无关系，
 * 于是 `x` 从 `W⁻` 跨到 `0⁺` 时会**跳变**，地上多出一道悬崖。
 * 想让「接缝两边严丝合缝」，噪声本身就必须**以 `W` 为周期**。
 *
 * ## 周期噪声怎么造（本项目选的法子）
 * 用**整数波数的平面波叠加**：
 *
 *     f(x,z) = Σᵢ Aᵢ · sin( 2π·(nxᵢ·x + nzᵢ·z) / W + φᵢ )       nxᵢ, nzᵢ ∈ ℤ
 *
 * `x → x + W` 时每一项的相位都前进 `2π·nxᵢ`，是 `2π` 的整数倍 ⇒ **每项各自周期为 `W`**，
 * 求和当然也以 `W` 为周期。数学上严格成立，不依赖任何取模技巧。
 *
 * 为什么不用「把 Perlin 的格点索引取模」：GPU 侧的 `mx_fractal_noise_float` 是 three 内置
 * MaterialX 函数（`node_modules/three/src/nodes/materialx/lib/mx_noise.js:834`），
 * 它内部的哈希改不了；而且**它只有 float / vec2 / vec3 三个重载，没有 vec4**
 * （`mx_perlin_noise_float_0` / `_1`，`:610` / `:630`），所以「用 4D 噪声把二维环面嵌进
 * 圆周」这条经典路子也走不通。⇒ 只剩「自己写一份周期噪声」。
 *
 * 选正弦叠加而不是自写周期 Perlin 的理由：**代价极低、且 CPU/GPU 天然逐字一致**。
 * `sin`/`cos` 在 TSL 里就是 `sin` / `cos`（`three/tsl`），两边写同一个式子即可，
 * 不存在「两份哈希实现相差 1 ulp ⇒ 道具浮空」的风险（那是本项目的头号铁律，见 `AGENT.md`）。
 *
 * ## 波数怎么选
 * 波数 `n` 对应波长 `λ = W / n`，而原实现的 `fractalNoise3` 用的是**频率** `f`（`λ = 1/f`）。
 * 换算：`n = round(W · f)`。本文件里所有波数都按这个式子从原来的频率推出来，
 * 所以换掉之后地形丘陵的疏密尺度**基本没变**，只是变成了严格周期。
 */

/**
 * 世界（环面）边长，米。
 *
 * `768 = 2⁸ × 3`，能被 1/2/3/4/6/8/12/16/24/32/48/64/96/128/192/256/384 整除
 * —— 各层格子的周期 `round(768 / cell)` 都落在整数量级上，误差最小。
 * 又是可视半径（雾 `far = 82 m`）的 9 倍以上，接缝远在天边。
 */
export const WORLD_SIZE = 768;

/** 把格子索引 `i` 折进 `[0, period)`（`period ≤ 0` 时原样返回）。 */
export function wrapIndex(i: number, period: number): number {
    if (!(period > 0)) return i;
    const m = i % period;
    return m < 0 ? m + period : m;
}

/**
 * **环面上的有向差**：`a - b` 折进 `[-WORLD_SIZE/2, +WORLD_SIZE/2)`。
 *
 * 这是「地图拼接」的数学形式：在环面上，`x = 768` 与 `x = 0` 是**同一个地方**。
 * 所有「到某个区域中心的距离」都必须走这个函数，否则区域（会场 / 月球）会在环面上
 * 被切成两半 —— 半边有、半边没有。
 *
 * ⚠️ 逐轴取 `tdiff` 得到的是**方形环面**（不是圆环面）。这不影响正确性：
 *   区域半径最大 62 m，而折返线在 ±384 m 处，那里权重早就已经是 0 了，
 *   所以折线处的「距离跳变」永远落在权重为 0 的区域里，看不见。
 */
export function tdiff(a: number, b: number): number {
    const d = a - b;
    return d - WORLD_SIZE * Math.round(d / WORLD_SIZE);
}

/** 一条平面波：`[nx, nz, 幅值, 相位]`。 */
export type Wave = readonly [number, number, number, number];

/**
 * **严格以 `WORLD_SIZE` 为周期**的标量噪声。
 *
 * @param waves 平面波表（见 `WILD_WAVES_L` / `WILD_WAVES_M` 等）
 * @param gain  整体倍率（用来把叠加结果归一化回原来 `fractalNoise3` 的量级）
 */
export function periodicWaves(x: number, z: number, waves: readonly Wave[], gain = 1): number {
    const k = (Math.PI * 2) / WORLD_SIZE;
    let s = 0;
    for (let i = 0; i < waves.length; i++) {
        const w = waves[i];
        s += w[2] * Math.sin(k * (w[0] * x + w[1] * z) + w[3]);
    }
    return s * gain;
}

