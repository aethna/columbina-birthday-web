/* ==================================================================
 * 一、接口
 * ================================================================== */

export interface NpcChat { id: string; name: string; lines: string[] }
export interface Letter { id: string; to: string; npcs: string[]; lines: string[] }
export type QuestKind = 'talk' | 'collect' | 'visit';
export interface Quest {
    id: string; npc: string; npcName: string; title: string;
    kind: QuestKind;
    desc: string;            // 【委托词 desc】，任务列表里显示的那一行
    needLabel: string;       // 目标提示
    offer: string[];         // 接取台词
    progress: string[];      // 进行中
    deliver: string[];       // 交付台词
    reward: string;
    targetNpc?: string;      // kind==='talk' 时：要对话的 NPC id
    pointId?: string;        // kind!=='talk' 时：互动点位 id
    count?: number;          // 需要几个（缺省 1）
}
export interface PointCopy { label: string; hint: string; okText: string }

